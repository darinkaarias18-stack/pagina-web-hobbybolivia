export async function seedCatalog() {
  console.log('🚀 Iniciando Seed y Migración de Catálogo Oficial (Categorías & Productos)...');

  // =========================================================================
  // 1. SINCRONIZACIÓN EN .data/db.json (Almacenamiento Local)
  // =========================================================================
  const dbPath = path.join(process.cwd(), '.data', 'db.json');
  if (fs.existsSync(dbPath)) {
    try {
      const raw = fs.readFileSync(dbPath, 'utf8');
      const db = JSON.parse(raw);

      const exchangeRate = Number(db.systemSettings?.exchangeRate) || 12.01;
      console.log(`💵 Tipo de Cambio de referencia: 1 USD = Bs. ${exchangeRate.toFixed(4)}`);

      // 1.1 Sincronizar Categorías Oficiales
      if (!Array.isArray(db.categories)) db.categories = [];
      for (const cat of OFFICIAL_CATEGORIES) {
        const idx = db.categories.findIndex((c: any) => c.slug === cat.slug || c.id === cat.id);
        if (idx >= 0) {
          db.categories[idx] = { ...db.categories[idx], ...cat };
        } else {
          db.categories.push(cat);
        }
      }

      // 1.2 Limpiar e Insertar Productos Oficiales con precios USD y cálculo en Bs. (preservando precios y stock existentes)
      const cleanedItems: any[] = OFFICIAL_PRODUCTS.map((prod, index) => {
        const existing = db.items?.find((i: any) => i.sku === prod.sku);
        const priceBob = existing && existing.price !== undefined ? existing.price : Number((prod.priceUsd * exchangeRate).toFixed(2));
        const priceUsd = existing && (existing.priceUsd !== undefined || existing.price_usd !== undefined)
          ? (existing.priceUsd ?? existing.price_usd)
          : prod.priceUsd;
        const stock = existing && (existing.stock !== undefined || existing.stockQuantity !== undefined)
          ? (existing.stock ?? existing.stockQuantity)
          : prod.stock;

        const resolvedImageUrl = prod.image_url || prod.imageUrl || null;

        return {
          id: index + 1,
          ...prod,
          price: priceBob,
          priceUsd: priceUsd,
          price_usd: priceUsd,
          stock: stock,
          stockQuantity: stock,
          imageUrl: resolvedImageUrl,
          image_url: resolvedImageUrl,
          images: resolvedImageUrl ? [resolvedImageUrl] : [],
          currency: 'USD',
          display_currency: 'USD',
          updated_at: new Date().toISOString()
        };
      });

      db.items = cleanedItems;

      // Recalcular conteo en categorías
      for (const cat of db.categories) {
        cat.itemCount = db.items.filter(
          (i: any) => (i.category_id === cat.id || i.categoryId === cat.id) && i.is_active !== false
        ).length;
      }

      fs.writeFileSync(dbPath, JSON.stringify(db, null, 2), 'utf8');
      console.log(`✅ ${cleanedItems.length} productos oficiales del catálogo cliente insertados en .data/db.json.`);
    } catch (err) {
      console.error('❌ Error actualizando .data/db.json:', err);
    }
  }

  // =========================================================================
  // 2. SINCRONIZACIÓN EN PRISMA (MySQL / MariaDB si DATABASE_URL está configurado)
  // =========================================================================
  if (process.env.DATABASE_URL) {
    try {
      console.log('🔄 Sincronizando con Prisma ORM / MariaDB...');

      // Upsert Categories con prisma.category.upsert
      const categoryMap: Record<number, number> = {};
      for (const cat of OFFICIAL_CATEGORIES) {
        const c = await prisma.category.upsert({
          where: { slug: cat.slug },
          update: {
            name: cat.name,
            description: cat.description,
            imageUrl: cat.imageUrl,
            order: cat.order,
            isActive: cat.isActive
          },
          create: {
            name: cat.name,
            slug: cat.slug,
            description: cat.description,
            imageUrl: cat.imageUrl,
            order: cat.order,
            isActive: cat.isActive
          }
        });
        categoryMap[cat.id] = c.id;
      }
      console.log(`✅ ${OFFICIAL_CATEGORIES.length} categorías registradas en Prisma.`);

      // Sincronización de productos usando prisma.product.upsert (evitando duplicados por SKU)
      const exchangeRate = 12.01;
      for (const prod of OFFICIAL_PRODUCTS) {
        const catId = categoryMap[prod.categoryId];
        if (catId) {
          const priceBob = Number((prod.priceUsd * exchangeRate).toFixed(2));

          await prisma.product.upsert({
            where: { sku: prod.sku },
            update: {
              name: prod.name,
              slug: prod.slug,
              categoryId: catId,
              scale: prod.scale,
              material: prod.material,
              specsLine: prod.specs_line,
              compatibleModels: prod.compatible_models,
              // Precios y stock preservados en update para no sobreescribir datos existentes en MariaDB
              imageUrl: prod.image_url || prod.imageUrl || null,
              isActive: prod.is_active ?? true,
              brand: prod.brand,
              description: prod.description
            },
            create: {
              sku: prod.sku,
              name: prod.name,
              slug: prod.slug,
              categoryId: catId,
              scale: prod.scale,
              material: prod.material,
              specsLine: prod.specs_line,
              compatibleModels: prod.compatible_models,
              price: priceBob,
              priceUsd: prod.priceUsd,
              stock: prod.stock,
              badge: prod.badge,
              imageUrl: prod.image_url || prod.imageUrl || null,
              isActive: prod.is_active ?? true,
              brand: prod.brand,
              description: prod.description
            }
          });
        }
      }
      console.log(`✅ ${OFFICIAL_PRODUCTS.length} productos oficiales sincronizados con prisma.product.upsert en MariaDB.`);
    } catch (e: any) {
      console.warn('⚠️ Nota sobre Prisma (MySQL/MariaDB no conectado o en standby):', e.message);
    }
  }

  console.log('🎉 Migración y Seed completados exitosamente.');
}

if (require.main === module) {
  seedCatalog()
    .catch((e) => {
      console.error(e);
      process.exit(1);
    })
    .finally(async () => {
      await prisma.$disconnect();
    });
}
